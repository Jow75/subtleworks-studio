import fs from 'node:fs'
import path from 'node:path'
import react from '@vitejs/plugin-react'
import { defineConfig, type Plugin } from 'vite'
import {
  INDEXABLE_PAGES,
  NOT_FOUND_META,
  ROUTE_ALIASES,
  SITE_URL,
  absoluteUrl,
  type PageMeta,
} from './src/data/siteMeta.ts'

const escapeAttribute = (value: string) =>
  value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/** Rewrites the head of the built index.html so it describes `meta` instead of the home page. */
function withPageMeta(html: string, meta: PageMeta): string {
  const url = absoluteUrl(meta.path)
  const image = absoluteUrl(meta.image)
  const setContent = (source: string, selector: string, value: string) =>
    source.replace(new RegExp(`(<meta ${selector} content=")[^"]*(")`), (_m, open: string, close: string) => open + escapeAttribute(value) + close)

  let out = html.replace(/<title>[^<]*<\/title>/, () => `<title>${escapeAttribute(meta.title)}</title>`)
  out = out.replace(/(<link rel="canonical" href=")[^"]*(")/, (_m, open: string, close: string) => open + escapeAttribute(url) + close)
  out = setContent(out, 'name="description"', meta.description)
  out = setContent(out, 'name="robots"', meta.noindex ? 'noindex' : 'index, follow')
  out = setContent(out, 'property="og:url"', url)
  out = setContent(out, 'property="og:title"', meta.title)
  out = setContent(out, 'property="og:description"', meta.description)
  out = setContent(out, 'property="og:image"', image)
  out = setContent(out, 'name="twitter:title"', meta.title)
  out = setContent(out, 'name="twitter:description"', meta.description)
  out = setContent(out, 'name="twitter:image"', image)
  return out
}

const prerenderedFile = (routePath: string) => `prerendered/${routePath.slice(1).replace(/\//g, '-')}.html`

/**
 * The app is a single-page app, so every route would otherwise be served the home page's
 * title, description and share image, and unknown URLs would answer 200. After the bundle
 * is written this plugin emits, from the one list of pages in src/data/siteMeta.ts:
 *   - prerendered/<route>.html : the app shell with that route's head tags
 *   - 404.html                 : the app shell marked noindex (served with HTTP 404)
 *   - _redirects               : Netlify rules mapping each route to its file, old product
 *                                URLs to the current ones, and everything else to 404.html
 *   - sitemap.xml, robots.txt
 */
function routeMetaPlugin(): Plugin {
  let outDir = 'dist'
  return {
    name: 'subtleworks-route-meta',
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir)
    },
    transformIndexHtml(html) {
      return html.replaceAll('%SITE_URL%', SITE_URL)
    },
    closeBundle() {
      const indexFile = path.join(outDir, 'index.html')
      if (!fs.existsSync(indexFile)) return
      const shell = fs.readFileSync(indexFile, 'utf8')
      const routes = INDEXABLE_PAGES.filter((page) => page.path !== '/')

      fs.mkdirSync(path.join(outDir, 'prerendered'), { recursive: true })
      for (const page of routes) {
        fs.writeFileSync(path.join(outDir, prerenderedFile(page.path)), withPageMeta(shell, page))
      }
      fs.writeFileSync(path.join(outDir, '404.html'), withPageMeta(shell, NOT_FOUND_META))

      const redirects = [
        '# Generated by vite.config.ts (routeMetaPlugin) from src/data/siteMeta.ts — do not edit.',
        ...ROUTE_ALIASES.map(({ from, to }) => `${from}  ${to}  301`),
        ...routes.map((page) => `${page.path}  /${prerenderedFile(page.path)}  200`),
        '/*  /404.html  404',
        '',
      ]
      fs.writeFileSync(path.join(outDir, '_redirects'), redirects.join('\n'))

      const today = new Date().toISOString().slice(0, 10)
      const sitemap = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        ...INDEXABLE_PAGES.map((page) => `  <url><loc>${absoluteUrl(page.path)}</loc><lastmod>${today}</lastmod></url>`),
        '</urlset>',
        '',
      ]
      fs.writeFileSync(path.join(outDir, 'sitemap.xml'), sitemap.join('\n'))
      fs.writeFileSync(
        path.join(outDir, 'robots.txt'),
        ['User-agent: *', 'Allow: /', 'Disallow: /prerendered/', '', `Sitemap: ${absoluteUrl('/sitemap.xml')}`, ''].join('\n'),
      )
    },
  }
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), routeMetaPlugin()],
})
